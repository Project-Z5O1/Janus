static int write_file_exact(const char* path, const uint8_t* data, size_t len) {
  FILE* f = fopen(path, "wb");
  if (f == NULL) {
    fprintf(stderr, "[HARNESS] staging: fopen(%s) failed: %s\n", path,
            strerror(errno));
    return -1;
  }
  if (len > 0 && fwrite(data, 1, len, f) != len) {
    fprintf(stderr, "[HARNESS] staging: fwrite(%s) failed: %s\n", path,
            strerror(errno));
    fclose(f);
    return -1;
  }
  if (fclose(f) != 0) {
    return -1;
  }
  return 0;
}



#define ES_NULL_ARRAY_SENTINEL 0xFF
#define ES_NULL_ELEM_SENTINEL  0xFFFF
#define ES_ELEM_MAX            0xFFFE

typedef struct {
    uint8_t* data;   
    size_t len;
    int is_null;     
} es_elem_t;

typedef struct {
    uint8_t* key;        
    size_t key_len;
    es_elem_t* elems;    
    size_t elem_count;
    int is_null_array;   
} es_args_t;

static void es_free(es_args_t* a) {
    size_t i;
    if (a->key) {
        free(a->key);
        a->key = NULL;
    }
    if (a->elems) {
        for (i = 0; i < a->elem_count; i++) {
            if (a->elems[i].data) {
                free(a->elems[i].data);
            }
        }
        free(a->elems);
        a->elems = NULL;
    }
    a->key = NULL;
    a->elem_count = 0;
}


static int es_parse(const uint8_t* buf, size_t len, es_args_t* out) {
    size_t off;
    size_t key_len, i;
    uint8_t count;
    memset(out, 0, sizeof(*out));
    if (len < 3) {
        return -1; 
    }
    key_len = (size_t)buf[0] | ((size_t)buf[1] << 8);
    off = 2;
    if (off + key_len > len) {
        return -1; 
    }
    out->key = (uint8_t*)malloc(key_len + 1); 
    if (out->key == NULL) {
        return -1;
    }
    memcpy(out->key, buf + off, key_len);
    out->key[key_len] = '\0'; 
    out->key_len = key_len;
    off += key_len;
    if (off + 1 > len) { 

        es_free(out);
        return -1; 
    }
    count = buf[off];
    off += 1;
    if (count == ES_NULL_ARRAY_SENTINEL) {
        out->is_null_array = 1; 
        return 0;
    }
    out->elem_count = (size_t)count;
    out->elems = (es_elem_t*)calloc(count ? count : 1, sizeof(es_elem_t));
    if (out->elems == NULL) {
        es_free(out);
        return -1;
    }
    for (i = 0; i < out->elem_count; i++) {
        size_t elen;
        if (off + 2 > len) {
            es_free(out);
            return -1; 
        }
        elen = (size_t)buf[off] | ((size_t)buf[off + 1] << 8);
        off += 2;
        if (elen == ES_NULL_ELEM_SENTINEL) {
            out->elems[i].is_null = 1;
            out->elems[i].data = NULL;
            out->elems[i].len = 0;
            continue;
        }
        if (off + elen > len) {
            es_free(out);
            return -1; 
        }
        out->elems[i].data = (uint8_t*)malloc(elen + 1); 
        if (out->elems[i].data == NULL) {
            es_free(out);
            return -1;
        }
        memcpy(out->elems[i].data, buf + off, elen);
        out->elems[i].data[elen] = '\0'; 
        out->elems[i].len = elen;
        off += elen;
    }
    return 0; 
}



#define ES_PARSE(buf, len, out) es_parse((buf), (len), (out))









static int es_construct(JNIEnv* env, const uint8_t* buf, size_t len,
                        jstring* out_key, jobjectArray* out_arr) {
    es_args_t a;
    jstring jkey = NULL;
    jobjectArray jarr = NULL;
    jclass cls = NULL;
    size_t i;

    if (es_parse(buf, len, &a) != 0) {
        return -1; 
    }
    


    jkey = (*env)->NewStringUTF(env, (const char*)a.key);
    if (jkey == NULL || (*env)->ExceptionCheck(env) == JNI_TRUE) {
        return -2;
    }
    if (a.is_null_array) {
        
        es_free(&a);
        *out_key = jkey;
        *out_arr = NULL;
        return 0;
    }
    cls = (*env)->FindClass(env, "java/lang/String");
    if (cls == NULL || (*env)->ExceptionCheck(env) == JNI_TRUE) {
        if ((*env)->ExceptionCheck(env) == JNI_TRUE) {
            (*env)->ExceptionClear(env);
        }
        (*env)->DeleteLocalRef(env, jkey);
        es_free(&a);
        return -2;
    }
    jarr = (*env)->NewObjectArray(env, (jsize)a.elem_count, cls, NULL);
    (*env)->DeleteLocalRef(env, cls);
    if (jarr == NULL || (*env)->ExceptionCheck(env) == JNI_TRUE) {
        if ((*env)->ExceptionCheck(env) == JNI_TRUE) {
            (*env)->ExceptionClear(env);
        }
        (*env)->DeleteLocalRef(env, jkey);
        es_free(&a);
        return -2;
    }
    for (i = 0; i < a.elem_count; i++) {
        jstring s;
        if (a.elems[i].is_null) {
            continue; 
        }
        
        s = (*env)->NewStringUTF(env, (const char*)a.elems[i].data);
        if (s == NULL || (*env)->ExceptionCheck(env) == JNI_TRUE) {
            if ((*env)->ExceptionCheck(env) == JNI_TRUE) {
                (*env)->ExceptionClear(env);
            }
            (*env)->DeleteLocalRef(env, jarr);
            (*env)->DeleteLocalRef(env, jkey);
            es_free(&a);
            return -2;
        }
        (*env)->SetObjectArrayElement(env, jarr, (jsize)i, s);
        (*env)->DeleteLocalRef(env, s);
        if ((*env)->ExceptionCheck(env) == JNI_TRUE) {
            (*env)->ExceptionClear(env);
            (*env)->DeleteLocalRef(env, jarr);
            (*env)->DeleteLocalRef(env, jkey);
            es_free(&a);
            return -2;
        }
    }
    es_free(&a);
    *out_key = jkey;
    *out_arr = jarr;
    return 0;
}



static char** es_strings_from_array(JNIEnv* env, jobjectArray arr,
                                    size_t* out_n) {
    jsize n;
    size_t i, j;
    char** out;
    if (arr == NULL) {
        *out_n = 0;
        return NULL;
    }
    n = (*env)->GetArrayLength(env, arr);
    out = (char**)calloc((size_t)(n > 0 ? n : 1), sizeof(char*));
    for (i = 0; i < (size_t)n; i++) {
        jstring s = (jstring)(*env)->GetObjectArrayElement(env, arr, (jsize)i);
        const char* p = s ? (*env)->GetStringUTFChars(env, s, NULL) : NULL;
        out[i] = p ? strdup(p) : strdup("(null)");
        if (p) {
            (*env)->ReleaseStringUTFChars(env, s, p);
        }
        if (s) {
            (*env)->DeleteLocalRef(env, s);
        }
    }
    for (i = 0; i + 1 < (size_t)n; i++) {
        for (j = i + 1; j < (size_t)n; j++) {
            if (strcmp(out[i], out[j]) > 0) {
                char* t = out[i];
                out[i] = out[j];
                out[j] = t;
            }
        }
    }
    *out_n = (size_t)n;
    return out;
}

static void es_free_strings(char** sv, size_t n) {
    size_t i;
    for (i = 0; i < n; i++) {
        free(sv[i]);
    }
    free(sv);
}






static void log_encode_result(JNIEnv* env, jlong handle, jboolean rc,
                              jobjectArray value, jstring jkey,
                              const char* store_path) {
  jsize count = -1;
  if (value == NULL) {
    fprintf(stderr, "[HARNESS] encodeSet(handle=%#llx, value=NULL-sentinel) "
                    "-> %s\n",
            (unsigned long long)handle, rc == JNI_TRUE ? "TRUE" : "FALSE");
  } else {
    count = (*env)->GetArrayLength(env, value);
    fprintf(stderr, "[HARNESS] encodeSet(handle=%#llx, value=String[%d]) "
                    "-> %s\n",
            (unsigned long long)handle, count, rc == JNI_TRUE ? "TRUE" : "FALSE");
  }
  if (g_trace_keys == 0) {
    return;
  }
  {
    struct stat st;
    const char* utf = (*env)->GetStringUTFChars(env, jkey, NULL);
    fprintf(stderr, "[HARNESS]   key=%s\n", utf ? utf : "(null)");
    if (utf != NULL) {
      (*env)->ReleaseStringUTFChars(env, jkey, utf);
    }
    if (store_path[0] != '\0' && stat(store_path, &st) == 0) {
      fprintf(stderr, "[HARNESS]   store %s size=%ld (staged 4096; growth = "
                      "ensureMemorySize/expandAndWriteBack)\n",
              store_path, (long)st.st_size);
    }
  }
}







